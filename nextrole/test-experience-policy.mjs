import assert from 'node:assert/strict';
import {experienceFit,experienceLabel} from './dist/experience-policy.mjs';
const make=(minimum,maximum=null)=>({description:`Required ${minimum}${maximum===null?'+':'–'+maximum} years of experience.`,experience_requirement:{status:'known',minimum,maximum,quote:`Required ${minimum}${maximum===null?'+':'–'+maximum} years of experience.`,quotes:[`Required ${minimum}${maximum===null?'+':'–'+maximum} years of experience.`],policy_version:'strict-experience-v2'}});
assert.equal(experienceFit(make(4),2),null);
assert.equal(experienceFit(make(3),2),null);
assert.equal(experienceFit(make(5),2),null);
assert.equal(experienceFit(make(2,4),5).status,'meets-minimum');
for(const [low,high] of [[0,1],[0,2],[1,1],[1,2]])assert.ok(experienceFit(make(low,high),2));
assert.equal(experienceFit(make(2.1,4),2),null);
assert.equal(experienceFit({years:2,description:'Experience unavailable'},2),null);
assert.equal(experienceFit({...make(2),description:'Unrelated description'},2),null);
assert.equal(experienceFit(make(2),'invalid'),null);
assert.equal(experienceLabel(make(4),2),'');
assert.equal(experienceFit(make(2),''),null);
assert.equal(experienceFit(make(2.1),2),null);
assert.equal(experienceFit(make(2),2).shortfall,0);
assert.equal(experienceFit({...make(3),experience_requirement:{...make(3).experience_requirement,policy_version:'within-two-years-v1'}},2),null);
assert.match(experienceLabel(make(2,4),2),/fit the stated 2–4/);
console.log('Strict experience boundaries, source evidence and stale stretch-result checks passed');
