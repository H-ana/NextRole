import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('./dist/semantic-worker.mjs',import.meta.url),'utf8');
let loads=0,embeddings=0;const messages=[];
const lib={env:{},pipeline:async(task,model,options)=>{loads++;assert.equal(model,'Xenova/all-MiniLM-L6-v2');options.progress_callback({status:'progress',progress:100});return async()=>{embeddings++;return {data:new Float32Array(384).fill(1)};};}};
const context=vm.createContext({Float32Array,self:{postMessage:m=>messages.push(m)},loadLibrary:async()=>lib});
vm.runInContext(source.replace(/import\('https:\/\/cdn\.jsdelivr\.net\/npm\/@huggingface\/transformers@3\.8\.1\/\+esm'\)/,'loadLibrary()'),context);
context.self.onmessage({data:{id:1,query:'Python automation',jobs:['Build Python automation']}});
await vm.runInContext('queue',context);
assert.equal(loads,1);assert.equal(lib.env.useBrowserCache,true);
assert(messages.some(m=>m.progress?.startsWith('Preparing on-device matching')));
assert(messages.some(m=>m.id===1&&m.scores?.length===1));
const firstEmbeddings=embeddings;messages.length=0;
context.self.onmessage({data:{id:2,query:'Python automation',jobs:['Build Python automation']}});
await vm.runInContext('queue',context);
assert.equal(loads,1,'Repeat searches reuse the loaded model');
assert.equal(embeddings,firstEmbeddings+1,'Repeat searches reuse job embeddings');
assert(messages.some(m=>m.progress==='Comparing your resume with jobs…'));
assert(!messages.some(m=>/download|preparing/i.test(m.progress||'')),'Warm searches show matching only');
assert(!source.includes('Downloading local matching model'));
const search=await readFile(new URL('./dist/public-search.mjs',import.meta.url),'utf8');
assert(!search.includes('Loading local matching model'));
console.log('Passed: cold initialization, warm model and job-vector reuse, accurate repeat-search statuses.');
