const file=new Blob(['%PDF-synthetic']);file.name='resume.pdf';
const payload={format:'nextrole-autofill',version:2,reviewed:true,profile:{firstName:'Alex',email:'alex@example.com'},sourceRevision:'website-only'};
const docs=globalThis.NextRoleAutofillDocuments;
const validated=await docs.validateTransfer({payload,resume:{name:file.name,size:file.size,base64:btoa(await file.text())}});
