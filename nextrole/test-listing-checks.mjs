import assert from 'node:assert/strict';
import {listingChecks,listingBadge,listingCheckPanel,eligibleListings} from './dist/listing-checks.mjs';
const now=Date.parse('2026-10-24T12:00:00Z'),day=86400000;
const base={id:'one',title:'Engineer',company:'Example',description:'Build production services and maintain APIs. '.repeat(30)};
const check=job=>listingChecks({...base,...job},now);
assert.equal(check({}).cautions,0);assert.equal(check({}).freshness,0);
assert.equal(check({}).signals.some(s=>s.id==='salary'),true,'No salary is information, not a scam warning');
assert.equal(check({min_amount:50000}).signals.some(s=>s.id==='salary'),false);
assert.equal(check({description:base.description+' Salary INR 50,000 per month.'}).signals.some(s=>s.id==='salary'),false);
assert.equal(check({description:'Please pay a registration fee before joining.'}).cautions,1);
assert.equal(check({description:'We never charge a registration fee. Beware of scams.'}).cautions,0);
assert.equal(check({description:'There is no application fee.'}).cautions,0);
assert.equal(check({description:'Please provide your OTP to complete registration.'}).cautions,1);
assert.equal(check({description:'Deposit our cheque and transfer the balance to us.'}).cautions,1);
assert.equal(check({description:'Contact hiring@gmail.com with your resume.'}).signals.some(s=>s.id==='personal-email'),true);
assert.equal(check({description:'Good opportunity.'}).signals.some(s=>s.id==='description'),true);
assert.equal(check({last_checked:(now-120*day)/1000}).freshness,0,'Collection dates are not publication or reposting dates');
assert.equal(check({date_posted:now-80*day}).freshness,1);
assert.equal(check({date_posted:now+80*day}).freshness,0);
const history={sites:{LinkedIn:{current_first_observed:(now-1*day)/1000,prior_postings:2,evidence:[{observed_at:(now-100*day)/1000,url:'https://linkedin.com/jobs/view/1'}]}}};
assert.equal(check({site_history:history}).signals.some(s=>s.id==='repeat-LinkedIn'),true);
history.sites.LinkedIn.prior_postings=1;
assert.equal(check({site_history:history}).signals.some(s=>s.id==='repeat-LinkedIn'),false,'One other listing is insufficient for recurring-posting flags');
assert.equal(listingBadge(base),'','Information gaps do not produce alarming card badges');
const panel=listingCheckPanel({...base,description:'Please pay a registration fee. <img src=x onerror=bad()>'});
assert.match(panel,/&lt;img/);assert.doesNotMatch(panel,/<img/);
assert.match(panel,/not independently verified/);assert.doesNotMatch(panel,/recruiter does not exist/i);
console.log('Passed: strong patterns with evidence; salary gaps are informational; negation; source dates; history-backed recurrence; safe rendering; recruiter identity remains unverified.');

const clean={...base,min_amount:50000};
const short={...base,description:'Build Python services.'};
assert.deepEqual(eligibleListings([base,clean,short,{...clean,description:clean.description+" Please pay a registration fee."},{...clean,date_posted:now-90*day}],now),[base,clean,short],"Keep missing salary and limited descriptions; hide scam patterns and stale postings");
assert.equal(eligibleListings([{...base,description:base.description+' Contact hiring@gmail.com with your resume.'}],now).length,1,'A personal email alone does not establish a ghost or scam listing');
