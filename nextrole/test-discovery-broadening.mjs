import assert from 'node:assert/strict';
import {recommendationExperience,experienceFit} from './dist/experience-policy.mjs';
import {filterPublicJobs,titleExperienceFit} from './dist/public-search.mjs';
import {canonicalCity,matchesPreferredCities} from './dist/locations.mjs';
import {roleAlignment} from './dist/role-alignment.mjs';
const description='Develop and deploy production AI agents and LLM applications using Python, APIs and model evaluation. Collaborate with engineering teams.';
const job={title:'AI Engineer',description,location:'Secunderabad, India',style:'Hybrid',experience_requirement:{status:'unknown',reason:'No explicit required experience band established'}};
assert.equal(recommendationExperience(job,2).group,'unknown');
assert.equal(experienceFit(job,2),null,'Unstated experience never becomes confirmed fit');
assert.equal(recommendationExperience(job,''),null);
assert.equal(recommendationExperience({...job,experience_requirement:{status:'unknown',reason:'Conflicting experience requirements'}},2),null);
assert.equal(recommendationExperience({...job,experience_requirement:{status:'unknown',reason:'Experience depends on an ambiguous or alternative qualification'}},2),null);
const prefs={experience:2,cities:['Hyderabad'],workstyle:'Hybrid'};
assert.equal(filterPublicJobs([job],prefs).length,1);
assert.equal(canonicalCity('Secunderabad'),'Hyderabad');
assert(!matchesPreferredCities('Mohali, India',['Chandigarh'],false,false));
assert(matchesPreferredCities('Mohali, India',['Chandigarh'],false,true));
assert(matchesPreferredCities('Noida, India',['New Delhi'],false,true));
assert(!matchesPreferredCities('Delhi, India',['Bengaluru'],false,true));
assert(matchesPreferredCities('Anywhere',['Bengaluru'],true,false));
assert.equal(filterPublicJobs([{...job,location:'Hosur, India'}],{...prefs,cities:['Bengaluru']}).length,0);
assert.equal(filterPublicJobs([{...job,location:'Hosur, India'}],{...prefs,cities:['Bengaluru'],include_nearby:true}).length,1);
assert(!titleExperienceFit('AI Engineer 3+ years',2));
assert.equal(filterPublicJobs([{...job,title:'AI Engineer 3+ years'}],prefs).length,0);
const intent={family:'ai'};
assert.equal(roleAlignment({...job,title:'Technology Consultant'},intent).kind,'description-supported');
for(const title of ['Support Consultant','Sales Consultant','Business Analyst','Product Manager','Incident Commander'])assert(!roleAlignment({...job,title},intent).aligned,title);
assert(!roleAlignment({...job,title:'Technology Consultant',description:'Skills: Python, AI, LLM, APIs, SQL. We offer a friendly workplace and competitive benefits.'},intent).aligned);
for(const title of ['Applied AI Engineer','AI Application Developer','LLM Application Engineer','Associate Software Engineer','SDE I','Software Engineer I'])assert(roleAlignment({...job,title},intent).aligned,title);
console.log('Unknown experience grouping, missing evidence, nearby opt-in, aliasing, title variants and description-based role checks passed.');

assert.equal(recommendationExperience({...job,description:'Requirements\n4+ years of experience building production software. '+description},2),null);
assert.equal(recommendationExperience({...job,description:'Preferred qualifications\n4+ years of experience building production software. '+description},2).group,'unknown');
