import assert from 'node:assert/strict';
import {assertResumeHeader} from './dist/resume-header.mjs';
import {formatSkillSections} from './dist/skill-format.mjs';
import {tailorResume} from './dist/resume-tools.mjs';
import {resumePreview} from './dist/resume-preview.mjs';
const original='Alex Example\n+91 9000012345 | alex@example.com | https://linkedin.com/in/example\n\nPROFILE\nBuilt Python services.\nSKILLS\nPython, SQL';
const draft=formatSkillSections(tailorResume(original,{skills:['Python']},['Python']).text);
assert(draft.startsWith('Alex Example\n+91 9000012345'));
assert(draft.includes('RELEVANT SKILLS\nPython\n\nPROFILE'));
assertResumeHeader(draft);
const preview=resumePreview(draft);
assert(preview.includes('<p class="resume-name">Alex Example</p>'));
assert(preview.includes('<p class="resume-section">RELEVANT SKILLS</p>'));
assert(!preview.includes('class="resume-name">RELEVANT SKILLS'));
const legacy='RELEVANT SKILLS\nPython\nAlex Example\nalex@example.com\nPROFILE\nBuilt Python services.';
assert(!formatSkillSections(legacy).includes('Python, Alex Example'));
assert.throws(()=>assertResumeHeader(legacy),/name must come before/);
assert.throws(()=>assertResumeHeader('Alex Example\nSKILLS\nPython, alex@example.com\nPROFILE\nSummary'),/Contact details/);
assert(!resumePreview('RELEVANT SKILLS\nPython\nPROFILE\nSummary').includes('class="resume-name"'));
console.log('Passed: name and contact stay above skills, legacy header corruption is blocked, and section headings cannot become the resume title.');
