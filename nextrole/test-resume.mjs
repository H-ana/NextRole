import assert from 'node:assert/strict';
// Pass the production module source on stdin to avoid Windows entry-path restrictions.
let source='';for await(const part of process.stdin)source+=part;
const {extract,contains,safeUrl,tailorResume,hasSkillOverlap,requiredYears,meetsKnownExperience}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(requiredYears('Minimum requirements\n7–14 years of experience in finance\nPreferred qualifications\n20 years of experience'),7);
assert.equal(requiredYears('3+ years of relevant engineering experience'),3);
assert.equal(requiredYears('Meet the minimum requirements. The preferred qualifications are a bonus.\nMinimum requirements\n7–14 years of experience\nPreferred qualifications\nFinance'),7);
assert.equal(requiredYears('Review the listing'),Infinity);
assert(!meetsKnownExperience(7,2));
assert(meetsKnownExperience(Infinity,2));
assert(hasSkillOverlap(['Python','SQL'],['python']));
assert(!hasSkillOverlap(['React'],['SQL']));
assert(contains('JavaScript, React, C++, C#','React'));
assert(!contains('JavaScript','Java'));
assert(!contains('reactive','React'));
assert(contains('C++, Python','C++'));
assert.equal(safeUrl('javascript:alert(1)'),null);
assert.equal(safeUrl('https://user:pass@example.com'),null);
assert.equal(safeUrl('https://careers.example.com/jobs/123'),'https://careers.example.com/jobs/123');
const resume='Alex Example\nEXPERIENCE\nEngineer, Example Co | 2021–2024\n• Built React interfaces; improved load times by 20%.\nEDUCATION\nBSc, Example University\nSKILLS\nReact, SQL';
const job={title:'Frontend Engineer',company:'Acme',skills:['React','TypeScript','SQL']};
const result=tailorResume(resume,job,['React','TypeScript','SQL']);
assert.deepEqual(result.selected,['React','SQL']);
assert.deepEqual(result.missing,['TypeScript']);
assert(!result.text.includes('TypeScript'));
assert.equal(result.text.replace('RELEVANT SKILLS\nReact, SQL\n\n',''),resume.replace('• ','- '));
assert(result.text.startsWith('Alex Example\nRELEVANT SKILLS'),'The skills index must follow the candidate header');
assert.equal(tailorResume(resume,job).text,resume.replace('• ','- '));
assert.equal(resume.includes('• Built'),true);
assert.throws(()=>tailorResume(' ',job));
assert.equal(extract('React and 3 years of experience').years,3);
assert(!tailorResume('No AWS experience.',{skills:['AWS']}).selected.length);
console.log('Passed: exact keyword boundaries, safe URLs, evidence-only skills, preserved facts and ordering, missing requirements, no implicit confirmation, empty source.');
